package com.josemaba.marquesitasapi.dto.request;

import com.josemaba.marquesitasapi.entity.PaymentMethod;
import jakarta.validation.Valid;
import jakarta.validation.constraints.NotEmpty;
import jakarta.validation.constraints.NotNull;
import java.time.LocalDateTime;
import java.util.List;
import java.util.UUID;

public record OrderRequest(

        @NotEmpty(message = "an order must contain at least one item")
        @Valid
        List<OrderItemRequest> items,

        String notes,

        String customerName,

        @NotNull(message = "paymentMethod is required")
        PaymentMethod paymentMethod,
        // Generated by the client so a retried create (e.g. after a lost response) is idempotent.
        UUID clientOrderId,
        // Moment the order was taken on the client; defaults to server time when absent (offline sync).
        LocalDateTime createdAt) {
}
